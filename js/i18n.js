  if (lang !== "tr" && lang !== "en") {
    lang = (navigator.language || "tr").toLowerCase().startsWith("tr") ? "tr" : "en";
  }

  window.I18N = STR;
  window.getLang = () => lang;
  window.setLang = (l) => {
    if (l !== "tr" && l !== "en") return;
    lang = l;
    localStorage.setItem(langKey, l);
    document.documentElement.lang = l;
  };
  window.t = (path, vars) => {
    let cur = STR[lang];
    for (const p of path.split(".")) {
      if (cur == null) break;
      cur = cur[p];
    }
    if (cur == null) {
      cur = STR.en;
      for (const p of path.split(".")) {
        if (cur == null) break;
        cur = cur[p];
      }
    }
    if (typeof cur !== "string") return path;
    return vars ? cur.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "") : cur;
  };
  window.loc = (obj) => {
    if (obj == null) return "";
    if (typeof obj === "string") return obj;
    return obj[lang] ?? obj.en ?? obj.tr ?? "";
  };
  window.fmtNum = (n, digits = 3) => {
    if (n == null || Number.isNaN(n)) return "—";
    if (typeof n !== "number") return String(n);
    if (n !== 0 && (Math.abs(n) < 0.001 || Math.abs(n) >= 1e7)) {
      return n.toExponential(Math.max(1, Math.min(3, digits))).replace("e+", "×10^").replace("e-", "×10^−");
    }
    return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", { maximumSignificantDigits: digits }).format(n);
  };
  window.escapeHtml = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
